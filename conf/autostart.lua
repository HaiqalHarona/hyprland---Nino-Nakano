hl.on("hyprland.start", function () 
   hl.exec_cmd("nm-applet")
   hl.exec_cmd("blueman-applet")
   hl.exec_cmd("mako")
   hl.exec_cmd("hypridle")
   hl.exec_cmd("swayosd-server")
   hl.exec_cmd("waybar")
   hl.exec_cmd("hyprpaper")
   -- Desktop widgets (Eww) & Auto-pause daemon for games/performance
   local home = os.getenv("HOME")
   hl.exec_cmd("eww daemon && eww open dashboard && eww open media_player")
   hl.exec_cmd(home .. "/.config/hypr/scripts/widget-pause.sh")
   -- Power profile auto-switcher (Performance on AC, Balanced on battery)
   hl.exec_cmd(home .. "/.config/hypr/scripts/auto-power.sh")
   -- Autostart Kitty on workspace 2 (keeps workspace 1 empty)
   hl.exec_cmd("kitty", { workspace = 2 })
   hl.dispatch(hl.dsp.focus({ workspace = 1 }))
   -- Clipboard history daemons (requires wl-clipboard + cliphist)
   hl.exec_cmd("wl-paste --type text --watch cliphist store")
   hl.exec_cmd("wl-paste --type image --watch cliphist store")
   -- GTK theming — applied via gsettings so KDE Plasma is NOT affected
   hl.exec_cmd("gsettings set org.gnome.desktop.interface gtk-theme 'catppuccin-mocha-mauve-standard+default'")
   hl.exec_cmd("gsettings set org.gnome.desktop.interface icon-theme 'Papirus-Dark'")
   hl.exec_cmd("gsettings set org.gnome.desktop.interface cursor-theme 'Catppuccin-Mocha-Mauve-Cursors'")
   hl.exec_cmd("gsettings set org.gnome.desktop.interface font-name 'Noto Sans 11'")
end)
